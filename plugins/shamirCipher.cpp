// РАЗДЕЛ 2: Тест простоты и генерация простых чисел
// ============================================================

// Один раунд теста простоты Миллера-Рабина.
// Проверяет, является ли n составным числом с помощью свидетеля a.
//
// Алгоритм:
// 1. Представляем n-1 = d * 2^r, где d — нечётное.
// 2. Вычисляем x = a^d mod n.
// 3. Если x = 1 или x = n-1, число n вероятно простое.
// 4. Иначе r-1 раз возводим x в квадрат и проверяем.
//
// Параметры:
//   n — проверяемое число
//   a — свидетель (основание для теста)
// Возвращает: true если n прошло тест (вероятно простое), false если составное
static bool millerRabinTest(uint64_t n, uint64_t a) {
    // Если n делится на свидетеля a, то n простое только если n == a
    // (например, isPrime(7) с свидетелем a=7: 7 % 7 = 0, но 7 простое)
    if (n % a == 0) return n == a;

    // Шаг 1: Представляем n-1 в виде d * 2^r
    uint64_t d = n - 1; // Начинаем с n-1
    int r = 0;          // Счётчик степени двойки

    // Делим d на 2, пока оно чётное, считая количество делений
    while ((d & 1) == 0) { // Проверяем младший бит: 0 = чётное
        d >>= 1;           // d = d / 2 (битовый сдвиг вправо)
        r++;               // Увеличиваем степень двойки
    }
    // Теперь n - 1 = d * 2^r, причём d — нечётное

    // Шаг 2: Вычисляем x = a^d mod n
    // Используем binMod из cryptoUtils для быстрого возведения
    uint64_t x = binMod(a, d, n);

    // Шаг 3: Если x = 1 или x = n-1, тест пройден — n вероятно простое
    if (x == 1 || x == n - 1) return true;

    // Шаг 4: Возводим x в квадрат r-1 раз и проверяем
    for (int i = 0; i < r - 1; ++i) {
        // x = x² mod n
        x = (x * x) % n;

        // Если x стало равно n-1, это означает, что a^(d·2^(i+1)) ≡ -1 (mod n),
        // что является признаком простоты
        if (x == n - 1) return true;
    }

    // Ни одна проверка не пройдена — n составное
    return false;
}

// Детерминированный тест простоты для чисел до 2^32.
// Использует набор свидетелей {2, 3, 5, 7, 11, 13},
// который гарантирует точность теста для всех чисел < 3.215·10⁹.
//
// В протоколе Шамира используется для:
// - проверки, что сгенерированное число p действительно простое;
// - гарантии, что шифрование/дешифрование будут корректны.
//
// Параметры:
//   n — проверяемое число
// Возвращает: true если n простое, false если составное
static bool isPrime(uint64_t n) {
    // 0 и 1 не являются простыми числами по определению
    if (n < 2) return false;

    // 2 и 3 — простые числа (проверяем отдельно, т.к. они особые)
    if (n < 4) return true;

    // Все чётные числа, кроме 2, являются составными
    if (n % 2 == 0) return false;

    // Набор свидетелей, гарантирующих точность для n < 2^32
    // Эти конкретные числа выбраны математически для покрытия всего диапазона
    uint64_t witnesses[] = {2, 3, 5, 7, 11, 13};

    // Проверяем n каждым свидетелем из списка
    for (uint64_t a : witnesses) {
        // Свидетель не может быть больше или равен проверяемому числу
        if (a >= n) break;

        // Если хотя бы один тест Миллера-Рабина провалился — n составное
        if (!millerRabinTest(n, a)) return false;
    }

    // Все тесты пройдены успешно — n является простым числом
    return true;
}

// Генерация случайного 32-битного числа.
// Стандартная функция rand() возвращает число до RAND_MAX (~15 бит),
// что недостаточно для генерации 32-битных простых чисел.
// Поэтому комбинируем 2 вызова rand() по 16 бит каждый.
//
// Возвращает: случайное 32-битное число
static uint64_t rand32() {
    uint64_t r = 0; // Результат — начинаем с нуля

    // Собираем 32 бита из двух 16-битных кусков
    for (int i = 0; i < 2; ++i) {
        // Сдвигаем текущий результат на 16 бит влево
        // и добавляем 16 младших бит от очередного вызова rand()
        r = (r << 16) | (static_cast<uint64_t>(rand()) & 0xFFFF);
    }

    return r; // Возвращаем 32-битное случайное число
}

// Генерация случайного простого числа заданной битности.
// Генерирует случайные нечётные числа в диапазоне [2^(bits-1), 2^bits - 1]
// и проверяет каждое на простоту тестом Миллера-Рабина.
//
// В протоколе Шамира используется для генерации простого модуля p.
// Чем больше bits, тем безопаснее шифрование (но медленнее).
//
// Параметры:
//   bits — желаемая битность числа (от 10 до 30)
// Возвращает: случайное простое число указанной битности
static uint64_t randomPrime(int bits) {
    // Ограничиваем битность разумными рамками
    if (bits < 10) bits = 10;  // Минимум: p > 256 (чтобы вместить любой байт)
    if (bits > 30) bits = 30;  // Максимум: чтобы избежать переполнения при умножении

    // Вычисляем диапазон чисел указанной битности:
    // low  = 2^(bits-1) — наименьшее число с bits битами (старший бит = 1)
    // high = 2^bits - 1  — наибольшее число с bits битами (все биты = 1)
    uint64_t low  = 1ULL << (bits - 1);
    uint64_t high = (1ULL << bits) - 1;

    // p в протоколе Шамира должно быть больше любого символа (> 255)
    if (low <= 256) low = 257;

    // Бесконечный цикл: генерируем кандидатов, пока не найдём простое
    while (true) {
        // Генерируем случайное число в диапазоне [low, high]
        uint64_t range = high - low + 1;
        uint64_t candidate = low + (rand32() % range);

        // Делаем число нечётным (все простые > 2 нечётные)
        if (candidate % 2 == 0) candidate |= 1; // Устанавливаем младший бит в 1

        // Проверяем, что число в допустимом диапазоне и является простым
        if (candidate <= high && isPrime(candidate)) {
            return candidate; // Нашли простое число!
        }
        // Если не простое — пробуем следующего кандидата
    }
}

