// ============================================================
// РАЗДЕЛ 1: Базовые криптоматематические функции (cryptoUtils)
// ============================================================
// Эти функции являются фундаментом для всех криптографических вычислений
// в протоколе Шамира: возведение в степень по модулю, нахождение НОД
// и модульного обратного элемента.
// Имена переменных и логика полностью соответствуют cryptoUtils.h.

// Вычисление наибольшего общего делителя (НОД) алгоритмом Евклида.
// Используется для проверки взаимной простоты чисел C и (p-1).
// Если gcd(C, p-1) = 1, то C обратим по модулю p-1,
// и существует D такое, что C*D ≡ 1 (mod p-1).
//
// Параметры:
//   a — первое число
//   b — второе число
// Возвращает: НОД(a, b)
uint64_t gcd(uint64_t a, uint64_t b)
{
    // Классический алгоритм Евклида:
    // на каждом шаге заменяем пару (a, b) на (b, a mod b),
    // пока b не станет равен 0
    while (b != 0)
    {
        uint64_t temp = b;  // Сохраняем текущее значение b
        b = a % b;          // Вычисляем остаток от деления a на b
        a = temp;           // Присваиваем a предыдущее значение b
    }
    // Когда b = 0, в переменной a находится НОД
    return a;
}

// Быстрое возведение в степень по модулю (бинарный метод).
// Вычисляет (base^power) mod modulo за O(log power) умножений.
// Это ключевая операция протокола Шамира:
//   шифрование  = binMod(m, C, p)
//   дешифрование = binMod(c, D, p)
//
// Параметры:
//   base   — основание степени (сообщение m или шифротекст c)
//   power  — показатель степени (секретная экспонента C или D)
//   modulo — модуль (простое число p)
// Возвращает: base^power mod modulo
uint64_t binMod(uint64_t base, uint64_t power, uint64_t modulo) {
    // Приводим основание по модулю, чтобы числа были меньше
    base %= modulo;

    // Применяем малую теорему Ферма: a^(p-1) ≡ 1 (mod p) для простого p.
    // Поэтому a^power ≡ a^(power mod (p-1)) (mod p),
    // что позволяет уменьшить показатель степени.
    power %= modulo - 1;

    // Начальное значение результата: любое число в степени 0 = 1
    uint64_t result = 1;

    // Цикл по битам показателя степени (от младшего бита к старшему)
    while (power > 0) {
        // Если младший бит степени равен 1, домножаем результат на текущее base
        // Пример: 13 = 1101₂, значит x^13 = x^8 · x^4 · x^1
        if (power & 1) {
            result = (result * base) % modulo;
        }

        // Возводим основание в квадрат: base → base²  → base⁴ → base⁸ → ...
        base = (base * base) % modulo;

        // Сдвигаем степень вправо: переходим к следующему биту
        power >>= 1;
    }

    // Возвращаем вычисленное значение base^power mod modulo
    return result;
}

// Нахождение модульного обратного элемента: x такой, что (base * x) mod modulo = 1.
// Реализовано через расширенный алгоритм Евклида (итеративная версия).
// В протоколе Шамира используется для вычисления D из C:
//   D = modNegative(C, p-1), т.е. D = C^(-1) mod (p-1)
//
// Параметры:
//   base   — число, для которого ищем обратное (экспонента C)
//   modulo — модуль (p-1)
// Возвращает: base^(-1) mod modulo, или 0 если обратного не существует
uint64_t modNegative(uint64_t base, uint64_t modulo) {
    // Приводим base по модулю, чтобы работать с числами меньше modulo
    base = base % modulo;

    // Сохраняем исходный модуль для финальной коррекции отрицательного результата
    uint64_t m0 = modulo;

    // Коэффициенты Безу: u1 и u2 — текущие значения, u3 — новое вычисляемое
    // В конце алгоритма u3 будет содержать искомый обратный элемент
    int64_t u1 = 0, u2 = 1, u3;

    // Начальные значения для алгоритма Евклида
    uint64_t q = modulo / base;  // Частное от деления modulo на base
    uint64_t r = modulo % base;  // Остаток от деления modulo на base
    uint64_t r0;                 // Переменная для хранения предыдущего остатка

    // Главный цикл расширенного алгоритма Евклида
    // Продолжаем, пока остаток не станет равен 0
    while (r > 0) {
        // Сохраняем текущий остаток (понадобится для проверки НОД в конце)
        r0 = r;

        // Вычисляем новый коэффициент Безу по рекуррентной формуле:
        // u3 = u1 - u2 * q
        u3 = u1 - u2 * q;

        // Сдвигаем переменные для следующей итерации алгоритма Евклида:
        // (modulo, base) ← (base, остаток)
        modulo = base;
        base = r;

        // Сдвигаем коэффициенты Безу:
        // (u1, u2) ← (u2, u3)
        u1 = u2;
        u2 = u3;

        // Вычисляем новое частное и остаток
        q = modulo / base;
        r = modulo % base;
    }

    // Проверяем, существует ли обратный элемент:
    // обратный существует только если НОД(base, modulo) = 1,
    // т.е. последний ненулевой остаток r0 должен быть равен 1
    if (r0 != 1) {
        return 0; // Обратного элемента не существует
    }

    // Если u3 положительное — это и есть ответ,
    // если отрицательное — прибавляем исходный модуль m0
    // для приведения к диапазону [0, m0-1]
    uint64_t result = (u3 > 0) ? u3 : u3 + m0;

    return result;
}

