// Разбор строки ключа формата "p,C" или "p,D".
// Ключ Шамира состоит из двух чисел, разделённых запятой:
// первое — простое число p (модуль), второе — экспонента C или D.
//
// Параметры:
//   key     — указатель на байтовый массив ключа
//   keySize — размер ключа в байтах
//   p       — выходной параметр: простое число p
//   exp     — выходной параметр: экспонента C или D
// Возвращает: true если разбор успешен, false при ошибке формата
static bool parsePair(const uint8_t* key, size_t keySize, uint64_t& p, uint64_t& exp) {
    // Копируем ключ в локальный буфер для безопасной работы со строками
    char buf[64] = {0}; // Буфер заполнен нулями

    // Проверяем, что ключ не слишком длинный (защита от переполнения буфера)
    if (keySize >= sizeof(buf)) return false;

    // Копируем байты ключа в char-буфер
    memcpy(buf, key, keySize);

    // Ищем запятую — разделитель между p и экспонентой
    char* comma = strchr(buf, ',');

    // Если запятой нет — формат ключа неверный
    if (!comma) return false;

    // Заменяем запятую на терминатор строки,
    // чтобы разделить буфер на две C-строки: "p\0C"
    *comma = '\0';

    // Преобразуем первую часть (до запятой) в число p
    // strtoull = string to unsigned long long
    p   = strtoull(buf, nullptr, 10);

    // Преобразуем вторую часть (после запятой) в экспоненту
    // comma + 1 указывает на символ сразу после бывшей запятой
    exp = strtoull(comma + 1, nullptr, 10);

    // Оба числа должны быть положительными для корректной работы
    return p > 0 && exp > 0;
}

